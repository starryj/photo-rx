def load_candidates() -> dict[str, dict]:
    blocks: dict[str, dict] = {}
    for fn in ["frameworks.md", "principles.md", "cases.md", "counter-examples.md", "glossary.md"]:
        text = (CAND / fn).read_text("utf-8")
        for raw in re.findall(r"```yaml\n(.*?)```", text, re.S):
            d = yaml.safe_load(raw)
            if isinstance(d, dict) and d.get("id"):
                blocks[d["id"]] = d
    return blocks


def main() -> int:
    cands = load_candidates()
    rows = []
    missing = []
    for cid, cand_id, claim, ctype, domain in SELECT:
        c = cands.get(cand_id)
        if not c:
            missing.append(cand_id)
            continue
        m = re.search(r"(p\d{3})", str(c.get("source_chapter", "")))
        if not m:
            missing.append(f"{cand_id}:page")
            continue
        rows.append({
            "id": cid,
            "page": PAGE_OVERRIDE.get(cid, m.group(1)),
            "type": ctype,
            "claim": claim,
            "source_chapter": c.get("source_chapter", ""),
            "quote": QUOTE_OVERRIDE.get(cid, str(c.get("source_quote", "")).strip()),
            "domain": domain,
        })
    if missing:
        print("MISSING", missing)
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(yaml.safe_dump(rows, allow_unicode=True, sort_keys=False, width=10000), "utf-8")
    print(f"wrote {OUT} n={len(rows)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
