    ('("fs13", ["框中框", "维度"]),', '("fs13", ["框架", "平面"]),'),
    ('("fs18", ["动态张力", "转瞬即逝"]),', '("fs18", ["持久"]),'),
    ('("fs19", ["图形", "背景", "反差"]),', '("fs19", ["模棱两可"]),'),
    ('("fs21", ["图案", "纹理", "十"]),', '("fs21", ["纹理", "图案"]),'),
    ('("fs23", ["递增", "递减", "透视"]),', '("fs23", ["透视", "加强"]),'),
    ('("fs27", ["扫视", "注意力"]),', '("fs27", ["眼睛", "注意"]),'),
    ('("fs29", ["两点", "隐含线"]),', '("fs29", ["两个", "更弱"]),'),
    ('("fs31", ["三角形", "有用"]),', '("fs31", ["三角形", "极易"]),'),
    ('("fs35", ["广角", "结构", "方式"]),', '("fs35", ["广角", "影响"]),'),
    ('("fs42", ["目的意图", "构图"]),', '("fs42", ["目的", "意图"]),'),
