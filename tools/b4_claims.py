def dump(path, rows):
    out = []
    for cid, page, kind, claim, quote in rows:
        out.append({
            "id": cid, "page": page, "type": kind, "claim": claim,
            "source_chapter": page, "source_quote": quote,
        })
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=1000), encoding="utf-8")
    print(f"{path.parent.parent.name}: {len(out)} 条 · {path}")


